def seed_db():
    # Ensure database tables exist without dropping existing user accounts
    Base.metadata.create_all(bind=engine)

    db: Session = SessionLocal()
    try:
        # Clear products table only for clean catalog updates
        db.query(Product).delete()
        db.commit()

        # 1. Ensure default demo_user context exists
        demo_user = db.query(User).filter(User.username == "demo_user").first()
        if not demo_user:
            demo_user = User(username="demo_user", is_verified=True)
            db.add(demo_user)
            db.commit()
            db.refresh(demo_user)

        # 2. Ensure default demo_user cart exists
        user_cart = db.query(Cart).filter(Cart.user_id == demo_user.id).first()
        if not user_cart:
            user_cart = Cart(user_id=demo_user.id)
            db.add(user_cart)
            db.commit()
        
        # 3. Add products
        for prod_data in PRODUCTS_SEED_DATA:
            product = Product(
                name=prod_data["name"],
                category=prod_data["category"],
                price=prod_data["price"],
                rating=prod_data["rating"],
                reviews_count=prod_data["reviews_count"],
                description=prod_data["description"],
                specifications=prod_data["specifications"],
                image_url=prod_data["image_url"],
                stock=prod_data["stock"]
            )
            db.add(product)
        
        db.commit()
        print(f"Database successfully seeded with {len(PRODUCTS_SEED_DATA)} products and a 'demo_user'!")
        
    except Exception as e:
        print(f"Error seeding database: {e}")
        db.rollback()
    finally:
        db.close()

if __name__ == "__main__":
    seed_db()
